#!/usr/bin/env python3
"""
Give the dashboard stylesheets a dark theme without changing the light one.

Every hard-coded colour that would read wrongly on a dark page is replaced by a
variable (`--dk-N` in dashboard.css, `--dks-N` in site.css) whose light value is the original colour, so light mode renders
exactly as before. A generated block then sets each variable's dark value, for
`:root[data-theme="dark"]` and for the system dark setting when no choice is stored.

Which colours change, by the property they sit in:
  - light backgrounds, borders and fills become dark surfaces of the same hue;
  - dark text becomes light text;
  - light text (it sits on dark olive panels), mid-tone accents, shadows, and faint
    white overlays (alpha <= 0.12, used on dark panels) are left as they are.

The design tokens in `:root` get hand-set dark values (TOKENS_DARK below). Re-run after
editing a stylesheet; the output is idempotent because the generated block is replaced.

  python3 scripts/site/build_dark_theme.py
"""

from __future__ import annotations

import colorsys
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
# Each file gets its own variable prefix: both load on the dashboard, and shared names would collide.
FILES = {ROOT / "assets" / "css" / "dashboard.css": "--dk-", ROOT / "assets" / "css" / "site.css": "--dks-"}
BEGIN, END = "/* ── dark theme (generated by scripts/site/build_dark_theme.py) ── */", "/* ── end dark theme ── */"

# Dark values for the design tokens (dashboard.css :root), matching the redesigned site's dark palette.
TOKENS_DARK = {
    "--bg": "#161a14", "--surface": "#1d221a", "--surface-alt": "#232920",
    "--border": "#3a4234", "--border2": "#4f5946", "--rule": "#3a4234",
    "--text": "#ece7da", "--text-dim": "#c9c3b3", "--text-muted": "#98927f", "--text-faint": "#6f6a5d",
    "--text-secondary": "#98927f",
    "--amber": "#e0a066", "--gold": "#e0a066",
    "--eggshell": "#161a14", "--eggshell-warm": "#1d221a", "--card-bg": "#232920",
    "--slate": "#ece7da", "--slate-mid": "#c9c3b3", "--gold-pale": "#1d221a", "--nearblack": "#ece7da",
    "--bg2": "#1d221a", "--surface2": "#232920", "--surface3": "#2a3126", "--border3": "#6f6a5d",
    "--olive-ink": "#c9d1b8",
    "--shadow": "0 10px 24px rgba(0, 0, 0, 0.25)", "--shadow-md": "0 18px 38px rgba(0, 0, 0, 0.35)",
    "--shell-shadow": "0 14px 30px rgba(0, 0, 0, 0.3)",
    "--paper-line": "rgba(236, 231, 218, 0.018)", "--paper-glow": "rgba(224, 160, 102, 0.05)",
}

# Rules a colour swap cannot express, written by hand for the dark theme.
MANUAL_DARK = [
    (".ov-title", "background:linear-gradient(135deg,#c9d1b8 0%,#a8ae72 40%,#d6a95a 80%,#e0a066 100%);"
                  "-webkit-background-clip:text;background-clip:text;"),
]

COLOR = re.compile(r"#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3}\b|rgba?\(\s*\d+\s*,\s*\d+\s*,\s*\d+\s*(?:,\s*[\d.]+\s*)?\)|\bwhite\b")
DECL = re.compile(r"([a-zA-Z-]+)\s*:([^;{}]*)")
SKIP_PROPS = {"box-shadow", "text-shadow", "filter", "--shadow", "--shadow-md", "--shell-shadow"}


def parse(c: str) -> tuple[tuple[int, int, int], float]:
    if c == "white":
        return (255, 255, 255), 1.0
    if c.startswith("#"):
        h = c[1:]
        if len(h) == 3:
            h = "".join(ch * 2 for ch in h)
        return (int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)), 1.0
    nums = [float(x) for x in re.findall(r"[\d.]+", c)]
    return (int(nums[0]), int(nums[1]), int(nums[2])), (nums[3] if len(nums) > 3 else 1.0)


def fmt(rgb, a: float) -> str:
    r, g, b = rgb
    return f"#{r:02x}{g:02x}{b:02x}" if a >= 1 else f"rgba({r},{g},{b},{a:g})"


def manual_rules() -> str:
    on = ':root[data-theme="dark"]'
    auto = ':root:not([data-theme="light"])'
    rules = "\n".join(f"{on} {sel}{{{decl}}}" for sel, decl in MANUAL_DARK)
    media = "\n".join(f"{auto} {sel}{{{decl}}}" for sel, decl in MANUAL_DARK)
    return f"{rules}\n@media (prefers-color-scheme: dark){{\n{media}\n}}\n"


def to_dark(rgb, a: float, prop: str, in_gradient: bool = False):
    """Dark counterpart of a colour in a given property, or None to leave it unchanged.
    Returns (rgb, alpha)."""
    if prop in SKIP_PROPS or prop.startswith("--"):
        return None
    if in_gradient and rgb == (255, 255, 255) and a <= 0.12:
        return rgb, min(a, 0.02)           # a faint white wash greys a whole dark page
    h, l, s = colorsys.rgb_to_hls(*(x / 255 for x in rgb))
    if prop == "color":
        if l < 0.32:                       # dark text → light text
            l2, s2 = 0.92 - l * 0.6, s * 0.5
        else:
            return None                    # light text sits on dark panels; mid tones read on both
    else:
        if l > 0.7:
            if a <= 0.12 and rgb == (255, 255, 255):
                return None                # faint white overlay on a dark panel
            l2, s2 = 0.075 + (1 - l) * 0.55, s * 0.45
        elif l < 0.25 and a < 0.5:
            l2, s2 = 0.88, s * 0.3         # faint dark rule or tint on paper → faint light rule
        else:
            return None                    # dark panels and accents stay
    r, g, b = colorsys.hls_to_rgb(h, l2, min(s2, 1))
    return (round(r * 255), round(g * 255), round(b * 255)), a


def restore(css: str, previous: dict) -> str:
    """Put back the original colours from a previous run, so every run starts from the source."""
    css = re.sub(r"\n?" + re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", "\n", css, flags=re.S)
    return re.sub(r"var\((--dks?-\d+)\)", lambda m: previous.get(m.group(1), m.group(0)), css)


def previous_values(css: str) -> dict:
    block = re.search(re.escape(BEGIN) + r"\s*:root\{(.*?)\}", css, flags=re.S)
    return dict(re.findall(r"(--dks?-\d+):([^;]+);", block.group(1))) if block else {}


def convert(css: str, registry: dict, tokens_seen: set, prefix: str = "--dk-") -> str:
    # Text set in the olive panel colour needs its own light counterpart.
    css = re.sub(r"(?<![\w-])color\s*:\s*var\(--olive-dark\)", "color:var(--olive-ink)", css)

    def decl(m: re.Match) -> str:
        prop, value = m.group(1).lower(), m.group(2)
        if prop.startswith("--"):
            tokens_seen.add(prop)
            return m.group(0)

        def col(cm: re.Match) -> str:
            rgb, a = parse(cm.group(0))
            dark = to_dark(rgb, a, prop, "gradient" in value)
            if dark is None:
                return cm.group(0)
            key = (fmt(rgb, a), fmt(*dark))
            if key not in registry:
                registry[key] = f"{prefix}{len(registry) + 1}"
            return f"var({registry[key]})"

        return f"{m.group(1)}:{COLOR.sub(col, value)}"

    # Only touch declarations inside rule bodies.
    out, depth, i = [], 0, 0
    for block in re.finditer(r"\{([^{}]*)\}", css):
        out.append(css[i:block.start(1)])
        # Comments can contain colons; only the code between them holds declarations.
        parts = re.split(r"(/\*.*?\*/)", block.group(1), flags=re.S)
        out.append("".join(p if p.startswith("/*") else DECL.sub(decl, p) for p in parts))
        i = block.end(1)
    out.append(css[i:])
    return "".join(out)


def block_for(registry: dict, tokens: dict, manual: str = "") -> str:
    light = "\n".join(f"  {var}:{light};" for (light, _), var in registry.items())
    dark = "\n".join(f"  {var}:{d};" for (_, d), var in registry.items())
    dark += "\n" + "\n".join(f"  {k}:{v};" for k, v in tokens.items())
    # site.css sets its tokens on .page (static pages), so the dark values are scoped there too.
    return (f"{BEGIN}\n:root{{\n  --olive-ink:#263221;\n{light}\n}}\n"
            f":root[data-theme=\"dark\"], :root[data-theme=\"dark\"] .page{{\n  color-scheme:dark;\n{dark}\n}}\n"
            f"@media (prefers-color-scheme: dark){{\n:root:not([data-theme=\"light\"]), :root:not([data-theme=\"light\"]) .page{{\n  color-scheme:dark;\n{dark}\n}}\n}}\n{manual}{END}\n")


def main() -> None:
    # Each stylesheet carries its own block: the static pages load site.css without dashboard.css.
    total = 0
    for f, prefix in FILES.items():
        css = f.read_text(encoding="utf-8")
        registry: dict = {}
        defined: set = set()
        out = convert(restore(css, previous_values(css)), registry, defined, prefix)
        tokens = {k: v for k, v in TOKENS_DARK.items() if k in defined or k == "--olive-ink"}
        manual = manual_rules() if prefix == "--dk-" else ""
        f.write_text(out.rstrip("\n") + "\n\n" + block_for(registry, tokens, manual), encoding="utf-8")
        total += len(registry)
        print(f"{f.relative_to(ROOT)}: {len(registry)} colours, {len(tokens)} tokens given dark values")


if __name__ == "__main__":
    main()
